type abacCase struct {
	Policy    string `json:"policy"`
	Agent     string `json:"agent"`
	Namespace string `json:"namespace"`
	Purpose   string `json:"purpose"`
	Action    string `json:"action"`
	Why       string `json:"why"`
	Allowed   bool   `json:"allowed"`
	Reason    string `json:"reason"`
}

// valid reports whether the vault layer accepts the case's identifiers
// (vectors include namespaces with '/', which the vault rejects up front).
func (c abacCase) valid(withPurpose bool) bool {
	if _, err := validation.ValidateAgent(c.Agent); err != nil {
		return false
	}
	if _, err := validation.ValidateNamespace(c.Namespace); err != nil {
		return false
	}
	if c.Purpose == "" {
		return !withPurpose
	}
	return validateParam(paramPurpose, c.Purpose, MaxPurposeChars, false) == nil
}

// TestABACVectorsThroughVault evaluates the G0 ABAC vectors (generated by
// the real ABACPolicyEngine) through the vault API: Simulate for every
// case, and Lease / SetSecret / RevokeSecret, which must allow or deny
// exactly as Python decided (deny precedence, default deny).
func TestABACVectorsThroughVault(t *testing.T) {
	ctx := context.Background()
	b, err := os.ReadFile(filepath.Join(pyvaultDir, "vectors", "abac.json"))
	if err != nil {
		t.Fatal(err)
	}
	var vec struct {
		Policies map[string]string `json:"policies"`
		Cases    []abacCase        `json:"cases"`
	}
	if err := json.Unmarshal(b, &vec); err != nil {
		t.Fatal(err)
	}

	type pv struct {
		v   *Vault
		cfg Config
	}
	vaults := map[string]*pv{}
	vaultFor := func(policy string) *Vault {
		if p, ok := vaults[policy]; ok {
			return p.v
		}
		dir := t.TempDir()
		prov := memProv()
		cfg := Config{DBPath: filepath.Join(dir, "vault.db"), Provider: prov, PolicyYAML: vec.Policies[policy]}
		// Seed one secret per namespace through an allow-all vault first.
		seed := openT(t, Config{DBPath: cfg.DBPath, Provider: prov, PolicyYAML: allowAllPolicy})
		for _, c := range vec.Cases {
			if c.Policy == policy && c.valid(false) {
				set(t, seed, c.Namespace, "target", "value")
			}
		}
		_ = seed.Close()
		v := openT(t, cfg)
		vaults[policy] = &pv{v, cfg}
		return v
	}

	checked := map[string]int{}
	for _, c := range vec.Cases {
		if !c.valid(false) {
			continue
		}
		v := vaultFor(c.Policy)
		d, err := v.Simulate(ctx, c.Agent, c.Namespace, c.Purpose, c.Action)
		if err != nil {
			t.Fatalf("%+v: %v", c, err)
		}
		if d.Allowed != c.Allowed || d.Reason != c.Reason {
			t.Errorf("simulate %s %s/%s/%s/%s: got %v %q, want %v %q (%s)", c.Policy, c.Agent, c.Namespace, c.Purpose,
				c.Action, d.Allowed, d.Reason, c.Allowed, c.Reason, c.Why)
		}
		checked["simulate"]++

		var opErr error
		switch c.Action {
		case "read":
			if !c.valid(true) {
				continue
			}
			opErr = v.Lease(ctx, LeaseRequest{Name: "target", Namespace: c.Namespace, Agent: c.Agent, Purpose: c.Purpose},
				func([]byte) error { return nil })
		case "write":
			opErr = v.SetSecret(ctx, SetSecretRequest{Name: "target", Namespace: c.Namespace, Agent: c.Agent,
				Purpose: c.Purpose, Value: []byte("new")})
		case "revoke":
			if c.Purpose != "*" {
				continue // the vault always evaluates revoke with purpose "*"
			}
			opErr = v.RevokeSecret(ctx, c.Namespace, "target", c.Agent)
		default:
			continue
		}
		checked[c.Action]++
		if c.Allowed && opErr != nil {
			t.Errorf("%s %s %+v: allowed by Python, vault error %v", c.Policy, c.Action, c, opErr)
		}
		if !c.Allowed {
			if !errors.Is(opErr, ErrPolicyDenied) {
				t.Errorf("%s %s %+v: denied by Python, vault returned %v", c.Policy, c.Action, c, opErr)
				continue
			}
			if r := lastAudit(t, v, 1)[0]; r.Action != "POLICY_DENIED" {
				t.Errorf("deny without POLICY_DENIED row (%s)", r.Action)
			}
		}
	}
	t.Logf("cases checked through the vault: %v", checked)
	if checked["simulate"] < 40 || checked["read"] < 20 || checked["write"] < 3 {
		t.Fatalf("too few vectors exercised: %v", checked)
	}
	for _, p := range vaults {
		mustVerify(t, p.v)
	}
}
